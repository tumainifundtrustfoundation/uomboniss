const makeF2Subject = (code: string, name: string, grade: 'A' | 'B' | 'C' | 'D' | 'F'): SubjectResult => {
  const pointsMap = { A: 1, B: 2, C: 3, D: 4, F: 5 };
  const scoreMap = { A: 82, B: 70, C: 54, D: 38, F: 22 };
  const remarksMap = {
    A: 'Bora Sana (Excellent)',
    B: 'Nzuri Sana (Very Good)',
    C: 'Nzuri (Good)',
    D: 'Inaridhisha (Satisfactory)',
    F: 'Hajaridhisha (Fail)',
  };
  return {
    code,
    name,
    nameEn: name,
    score: scoreMap[grade],
    grade,
    points: pointsMap[grade],
    remarks: remarksMap[grade],
  };
};

